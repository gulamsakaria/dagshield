const dictionaries: Record<Lang, Record<Key, string>> = { en, bn };

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, params?: Record<string, string | number>) => string;
  pick: (en: string, bn: string) => string;
}

const I18nContext = createContext<Ctx | null>(null);

function readStoredLang(): Lang {
  try {
    return localStorage.getItem("dagshield_lang") === "bn" ? "bn" : "en";
  } catch {
    return "en";
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("dagshield_lang", l);
    } catch {
      /* not remembered */
    }
  }, []);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      setLang,
      t: (key, params) => {
        let text: string = dictionaries[lang][key];
        for (const [k, v] of Object.entries(params ?? {}))
          text = text.replaceAll(`{${k}}`, String(v));
        return text;
      },
      pick: (e, b) => (lang === "bn" ? b : e),
    }),
    [lang, setLang],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
